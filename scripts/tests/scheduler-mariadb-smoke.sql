INSERT INTO SMOKE_CMPET (HOUSE_MANAGE_NO, MODEL_NO, REQ_CNT) VALUES ('H1', '01', '20') ON DUPLICATE KEY UPDATE REQ_CNT = VALUES(REQ_CNT);

-- AdminScheduleManager.seed: FROM 없는 INSERT ... SELECT ... WHERE NOT EXISTS (두 번 실행해도 한 행)
CREATE TEMPORARY TABLE SMOKE_SCHEDULE (JOB_KIND VARCHAR(24) NOT NULL PRIMARY KEY, ENABLED BOOLEAN NOT NULL, CRON_EXPRESSION VARCHAR(100) NOT NULL, LOOKBACK_DAYS INT NOT NULL, UPDATED_AT DATETIME(6) NOT NULL);
INSERT INTO SMOKE_SCHEDULE (JOB_KIND, ENABLED, CRON_EXPRESSION, LOOKBACK_DAYS, UPDATED_AT)
SELECT 'SYNC', TRUE, '0 15 3 * * *', 90, NOW(6) WHERE NOT EXISTS (SELECT 1 FROM SMOKE_SCHEDULE WHERE JOB_KIND = 'SYNC');
INSERT INTO SMOKE_SCHEDULE (JOB_KIND, ENABLED, CRON_EXPRESSION, LOOKBACK_DAYS, UPDATED_AT)
SELECT 'SYNC', TRUE, '0 15 3 * * *', 90, NOW(6) WHERE NOT EXISTS (SELECT 1 FROM SMOKE_SCHEDULE WHERE JOB_KIND = 'SYNC');

-- DataRetentionJob: 다른 테이블을 보는 NOT EXISTS와 LIMIT이 붙은 DELETE(처리 대기 신고가 걸린 쪽지는 남긴다)
CREATE TEMPORARY TABLE SMOKE_MESSAGE (MESSAGE_SEQ BIGINT NOT NULL PRIMARY KEY, REG_DT DATETIME(6) NOT NULL);
CREATE TEMPORARY TABLE SMOKE_REPORT (TARGET_TYPE VARCHAR(10) NOT NULL, TARGET_SEQ BIGINT NOT NULL, STATUS VARCHAR(10) NOT NULL);
INSERT INTO SMOKE_MESSAGE VALUES (1, NOW(6) - INTERVAL 200 DAY), (2, NOW(6) - INTERVAL 200 DAY), (3, NOW(6) - INTERVAL 200 DAY);
INSERT INTO SMOKE_REPORT VALUES ('MESSAGE', 1, 'OPEN'), ('MESSAGE', 2, 'DONE');
DELETE FROM SMOKE_MESSAGE WHERE REG_DT < NOW(6) - INTERVAL 180 DAY AND NOT EXISTS (SELECT 1 FROM SMOKE_REPORT R WHERE R.TARGET_TYPE='MESSAGE'
  AND R.TARGET_SEQ=SMOKE_MESSAGE.MESSAGE_SEQ AND R.STATUS='OPEN') LIMIT 10000;

SELECT REQ_CNT INTO @req FROM SMOKE_CMPET;
SELECT COUNT(*) INTO @schedules FROM SMOKE_SCHEDULE;
SELECT GROUP_CONCAT(MESSAGE_SEQ ORDER BY MESSAGE_SEQ) INTO @messages FROM SMOKE_MESSAGE;
SELECT CONCAT('lock=', @got_lock, ' release=', @released, ' req=', @req, ' schedules=', @schedules, ' messages=', @messages) AS result;
