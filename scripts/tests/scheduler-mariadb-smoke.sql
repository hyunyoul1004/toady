-- 마지막 줄 결과가 'lock=1 release=1 req=20 schedules=1 messages=1'이어야 한다.

-- ApplyhomeSyncLock: 수집 동시 실행 방지 잠금
SELECT GET_LOCK('toady-ci-smoke', 0) INTO @got_lock;
SELECT RELEASE_LOCK('toady-ci-smoke') INTO @released;

